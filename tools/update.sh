#!/usr/bin/env bash
# Regenerates the manifest of every app that follows an upstream GitHub release:
# apps/<app-id>/upstream holds "owner/repo". The manifest is upstream's own
# packaging/linux/flatpak/*.bundle.yml at the latest release tag, with its
# `dir: stage` source swapped for the release's linux-x86_64 tarball.
# Apps with apps/<app-id>/pypi ("package") instead get the "<package>==<version>"
# pin in their hand-written manifest bumped to the latest PyPI release.
# Prints the IDs of the apps whose manifest changed.
#   tools/update.sh [APP-ID...]     (default: every app with an upstream or pypi file)
# Needs gh (GH_TOKEN in CI), curl and python3.
set -Eeuo pipefail
cd "$(dirname "$0")/.."
apps=("$@")
((${#apps[@]})) || for f in apps/*/upstream apps/*/pypi; do [[ -f $f ]] && apps+=("$(basename "$(dirname "$f")")"); done

for id in "${apps[@]}"; do
  if [[ -f apps/$id/pypi ]]; then
    pkg=$(<"apps/$id/pypi")
    v=$(curl -fsSL "https://pypi.org/pypi/$pkg/json" | python3 -c 'import json, sys; print(json.load(sys.stdin)["info"]["version"])')
    m=apps/$id/$id.yml
    grep -q "$pkg==" "$m" || { echo "$m has no $pkg== pin" >&2; exit 1; }
    grep -qE "$pkg==$v( |$)" "$m" || { sed -i.bak -E "s/($pkg==)[^ ]+/\1$v/" "$m" && rm "$m.bak" && echo "$id"; }
    continue
  fi
  repo=$(<"apps/$id/upstream")
  tag=$(gh release view -R "$repo" --json tagName -q .tagName)
  path=$(gh api "repos/$repo/git/trees/$tag?recursive=1" -q '.tree[].path' | grep -E 'flatpak/[^/]*\.bundle\.ya?ml$' | head -1)
  [[ -n $path ]] || { echo "$repo $tag: no flatpak bundle manifest" >&2; exit 1; }
  # The app's own tarball: its name is shorter than the -cli/-server ones.
  asset=$(gh release view -R "$repo" "$tag" --json assets -q '.assets[].name' | grep -E 'linux-x86_64\.tar\.gz$' | awk '{print length, $0}' | sort -n | head -1 | cut -d' ' -f2)
  url=https://github.com/$repo/releases/download/$tag/$asset
  sha=$(gh release download -R "$repo" "$tag" -p SHA256SUMS.txt -O - 2>/dev/null | awk -v a="$asset" '$2 == a {print $1}')
  [[ -n $sha ]] || sha=$(curl -fsSL "$url" | sha256sum | cut -d' ' -f1)

  out=apps/$id/$id.yml
  {
    echo "# Generated by tools/update.sh from $repo $tag ($path). Do not edit by hand."
    gh api "repos/$repo/contents/$path?ref=$tag" -q .content | base64 -d |
      URL=$url SHA=$sha perl -0pe 's/^(\s*)- type: dir\n\s*path: stage\n/$1- type: archive\n$1  url: $ENV{URL}\n$1  sha256: $ENV{SHA}\n/m or die "no stage source\n"'
  } > "$out.new"
  grep -q "^id: $id$" "$out.new" || { echo "$path is not $id" >&2; rm "$out.new"; exit 1; }
  if cmp -s "$out.new" "$out"; then rm "$out.new"; else mv "$out.new" "$out"; echo "$id"; fi
done
